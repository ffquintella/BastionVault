fn in_list(list: &[&str], name: &str) -> bool {
    list.contains(&name)
}

/// Refused whatever schema the name is in.
pub(crate) fn always_refused(name: &str) -> bool {
    in_list(ALWAYS_REFUSED, name) || ALWAYS_REFUSED_PREFIXES.iter().any(|p| name.starts_with(p))
}

/// Runs SQL text: opaque `sql_execute` whatever schema the name is in.
pub(crate) fn dynamic_sql(name: &str) -> bool {
    in_list(DYNAMIC_SQL, name)
}

/// The class of a `pg_catalog` function by its canonical name.
pub(crate) fn class(name: &str) -> FnClass {
    match name {
        "nextval" | "setval" => FnClass::SequenceWrite,
        "currval" => FnClass::SequenceRead,
        "lastval" => FnClass::LastValue,
        "set_config" => FnClass::SetConfig,
        "pg_notify" => FnClass::Notify,
        _ if in_list(ADVISORY_LOCKS, name) => FnClass::AdvisoryLock,
        _ if in_list(ADMIN, name) || ADMIN_PREFIXES.iter().any(|p| name.starts_with(p)) => FnClass::Admin,
        _ if in_list(PURE, name) => FnClass::Pure,
        _ => FnClass::Unknown,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_do_not_overlap() {
        for n in PURE {
            assert!(!always_refused(n) && !dynamic_sql(n), "{n}");
            assert!(!in_list(ADMIN, n) && !in_list(ADVISORY_LOCKS, n), "{n}");
            assert!(!matches!(*n, "nextval" | "setval" | "currval" | "lastval" | "set_config" | "pg_notify"), "{n}");
            assert_eq!(*n, n.to_ascii_lowercase(), "table names are canonical");
        }
        assert!(always_refused("dblink_exec"));
        assert_eq!(class("lo_unlink"), FnClass::Unknown);
    }
}
