//! The PostgreSQL function table (§4.3, side-effecting functions).
//!
//! Known writers map to their real capability, known dangerous ones to the
//! always-refused list, a reviewed set of built-ins to nothing, and every
//! other name to user code (`sql_execute`, or `sql_select` in a session the
//! database keeps read-only). The table never defaults a name to harmless.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum FnClass {
    /// Reviewed built-in with no side effect beyond reading its arguments.
    Pure,
    /// `sql_admin` on `sql/server`.
    Admin,
    /// `nextval`, `setval`: `sql_update` on the sequence named by argument 1.
    SequenceWrite,
    /// `currval`: `sql_select` on the sequence named by argument 1.
    SequenceRead,
    /// `lastval`: `sql_select` on `sql/server` (the sequence is not named).
    LastValue,
    /// Advisory locks: `sql_update` on `sql/server`.
    AdvisoryLock,
    /// `set_config`: classified like `SET` of argument 1.
    SetConfig,
    /// `pg_notify`: `sql_execute` on `sql/server`.
    Notify,
    /// Not in the table: user code.
    Unknown,
}

