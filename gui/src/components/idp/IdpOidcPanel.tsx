import { useCallback, useEffect, useState } from "react";
import { Badge, Button, Card, ConfirmModal, Input, Modal, Select, Table, Textarea, useToast } from "../ui";
import { SettingsForm, type FieldSpec } from "./SettingsForm";
import { KeyRingCard } from "./KeyRingCard";
import { OneTimeSecretModal, useOneTimeSecret } from "./OneTimeSecretModal";
import { CopyValue, environmentOptions } from "./IdpShared";
import type { IdpDirectory } from "./directory";
import * as idp from "../../lib/idp";

const OIDC_FIELDS: FieldSpec[] = [
  { key: "enabled", label: "Issue codes and tokens", kind: "bool" },
  { key: "issuer", label: "Issuer", kind: "text", full: true, placeholder: "https://vault.example.com/v2/idp/oidc", hint: "https, no trailing slash: the iss of every token." },
  { key: "authorization_endpoint", label: "Authorization page", kind: "text", full: true, hint: "Browser-facing page that relays to v2/idp/oidc/authorize (default <issuer>/authorize)." },
  { key: "id_token_ttl", label: "ID token lifetime", kind: "duration", hint: "1m–1h, default 5m." },
  { key: "code_ttl", label: "Code lifetime", kind: "duration", hint: "10s–10m, default 60s." },
];

type Row = { name: string; info: idp.IdpOidcClientInfo };

function ClientModal({
  client,
  environments,
  onClose,
  onSaved,
}: {
  client: idp.IdpOidcClient | null;
  environments: string[];
  onClose: () => void;
  onSaved: (c: idp.IdpOidcClient) => void;
}) {
  const creating = client === null;
  const [clientId, setClientId] = useState(client?.client_id ?? "");
  const [environment, setEnvironment] = useState(client?.environment ?? "");
  const [redirects, setRedirects] = useState((client?.redirect_uris ?? []).join("\n"));
  const [initiate, setInitiate] = useState(client?.initiate_login_uri ?? "");
  const [description, setDescription] = useState(client?.description ?? "");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function save() {
    setError(null);
    const body: Record<string, unknown> = {
      redirect_uris: idp.splitList(redirects),
      initiate_login_uri: initiate.trim(),
      description: description.trim(),
    };
    if (creating) body.environment = environment;
    setBusy(true);
    try {
      onSaved((await idp.idpWrite<idp.IdpOidcClient>("oidc_client", creating ? clientId.trim() : client.client_id, body)).data);
    } catch (e) {
      setError(idp.describeIdpError(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <Modal
      open
      onClose={onClose}
      title={creating ? "Register a relying party" : `Client ${client.client_id}`}
      size="lg"
      actions={
        <>
          <Button variant="ghost" onClick={onClose}>Cancel</Button>
          <Button onClick={() => void save()} loading={busy}>{creating ? "Register" : "Save"}</Button>
        </>
      }
    >
      <div className="grid grid-cols-2 gap-3">
        <div className="col-span-2 sm:col-span-1">
          <Input label="Client id" value={clientId} disabled={!creating} onChange={(e) => setClientId(e.target.value)} />
        </div>
        <div className="col-span-2 sm:col-span-1">
          <Select label="Environment" value={environment} disabled={!creating} onChange={(e) => setEnvironment(e.target.value)} options={environmentOptions(creating ? environments : [environment])} />
        </div>
        <div className="col-span-2">
          <Textarea label="Redirect URIs (one per line, https, matched exactly)" value={redirects} onChange={(e) => setRedirects(e.target.value)} className="min-h-[80px]" />
        </div>
        <div className="col-span-2">
          <Input label="Initiate login URI (optional)" value={initiate} onChange={(e) => setInitiate(e.target.value)} />
        </div>
        <div className="col-span-2">
          <Input label="Description" value={description} onChange={(e) => setDescription(e.target.value)} />
        </div>
        {creating && <p className="col-span-2 text-xs text-[var(--color-text-muted)]">The client secret is generated by the vault and shown once.</p>}
        {error && <p className="col-span-2 text-sm text-[var(--color-danger)] break-words" role="alert">{error}</p>}
      </div>
    </Modal>
  );
}

export function IdpOidcPanel({ directory }: { directory: IdpDirectory }) {
  const { toast } = useToast();
  const [cfg, setCfg] = useState<idp.IdpOidcConfig | null>(null);
  const [rows, setRows] = useState<Row[]>([]);
  const [editing, setEditing] = useState<idp.IdpOidcClient | null | undefined>(undefined);
  const [rotating, setRotating] = useState<string | null>(null);
  const [deleting, setDeleting] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const secret = useOneTimeSecret();

  const load = useCallback(async () => {
    try {
      const [c, list] = await Promise.all([idp.idpReadSettings<idp.IdpOidcConfig>("oidc"), idp.idpList<idp.IdpOidcClientInfo>("oidc_client")]);
      setCfg(c.data);
      setRows(list.keys.map((name) => ({ name, info: list.key_info[name] })).filter((r) => r.info !== undefined));
    } catch (e) {
      toast("error", idp.describeIdpError(e));
    }
  }, [toast]);

  useEffect(() => {
    void load();
  }, [load]);

  function showSecret(c: idp.IdpOidcClient) {
    if (!c.client_secret) return;
    secret.show({
      title: `Client secret for ${c.client_id}`,
      label: "Client secret",
      value: c.client_secret,
      details: [["Client id", c.client_id], ["Environment", c.environment]],
      notice: "Store it in the relying party now: the vault keeps only its hash and cannot show it again.",
    });
  }

  async function openEdit(name: string) {
    try {
      setEditing((await idp.idpRead<idp.IdpOidcClient>("oidc_client", name)).data);
    } catch (e) {
      toast("error", idp.describeIdpError(e));
    }
  }

  async function act(kind: "rotate" | "delete") {
    const name = kind === "rotate" ? rotating : deleting;
    if (!name) return;
    setBusy(true);
    try {
      if (kind === "rotate") showSecret((await idp.idpWrite<idp.IdpOidcClient>("oidc_client", name, { rotate_secret: true })).data);
      else await idp.idpDelete("oidc_client", name);
      toast("success", kind === "rotate" ? `New secret minted for ${name}` : `Client ${name} removed`);
      await load();
    } catch (e) {
      toast("error", idp.describeIdpError(e));
    } finally {
      setBusy(false);
      setRotating(null);
      setDeleting(null);
    }
  }

  async function save(body: Record<string, unknown>) {
    setCfg((await idp.idpWriteSettings<idp.IdpOidcConfig>("oidc", body)).data);
    toast("success", "OIDC provider settings saved");
  }

  return (
    <div className="space-y-4">
      <Card title="OpenID Provider" actions={<Badge variant={cfg?.enabled ? "success" : "neutral"} label={cfg?.enabled ? "enabled" : "disabled"} />}>
        <div className="space-y-3">
          {cfg?.issuer && <CopyValue label="discovery" value={`${cfg.issuer}/.well-known/openid-configuration`} />}
          <SettingsForm fields={OIDC_FIELDS} current={cfg as unknown as Record<string, unknown>} onSave={save} />
          <p className="text-xs text-[var(--color-text-muted)]">
            The vault answers in its JSON envelope: a standard relying party needs a relay or HTTP adapter to fetch
            discovery and post to the token endpoint.
          </p>
        </div>
      </Card>
      <KeyRingCard ring="oidc" />
      <Card title="Relying parties" actions={<Button size="sm" onClick={() => setEditing(null)}>Register client</Button>}>
        <Table<Row>
          tableClassName="table-fixed"
          data={rows}
          rowKey={(r) => r.name}
          emptyMessage="No relying party registered"
          columns={[
            { key: "id", header: "Client id", className: "w-1/4", render: (r) => <div className="truncate font-medium" title={r.name}>{r.name}</div> },
            { key: "env", header: "Environment", className: "w-1/6", render: (r) => <div className="truncate">{r.info.environment}</div> },
            { key: "uris", header: "Redirect URIs", render: (r) => <div className="truncate font-mono text-xs" title={r.info.redirect_uris.join("\n")}>{r.info.redirect_uris.join(", ")}</div> },
            {
              key: "actions",
              header: "",
              className: "w-64",
              render: (r) => (
                <div className="flex justify-end gap-2">
                  <Button size="sm" variant="ghost" onClick={() => void openEdit(r.name)}>Edit</Button>
                  <Button size="sm" variant="secondary" onClick={() => setRotating(r.name)}>New secret</Button>
                  <Button size="sm" variant="danger" onClick={() => setDeleting(r.name)}>Remove</Button>
                </div>
              ),
            },
          ]}
        />
      </Card>
      {editing !== undefined && (
        <ClientModal
          client={editing}
          environments={directory.activeEnvironments}
          onClose={() => setEditing(undefined)}
          onSaved={(c) => {
            setEditing(undefined);
            toast("success", `Client ${c.client_id} saved`);
            showSecret(c);
            void load();
          }}
        />
      )}
      <ConfirmModal
        open={rotating !== null}
        onClose={() => setRotating(null)}
        onConfirm={() => void act("rotate")}
        loading={busy}
        title={`New secret for ${rotating ?? ""}`}
        message={`Mint a new client secret for "${rotating ?? ""}"? The current secret stops working at once; the relying party fails to redeem codes until it is given the new one.`}
        confirmLabel="Mint new secret"
      />
      <ConfirmModal
        open={deleting !== null}
        onClose={() => setDeleting(null)}
        onConfirm={() => void act("delete")}
        loading={busy}
        title={`Remove client ${deleting ?? ""}`}
        message={`Remove "${deleting ?? ""}"? Nobody can sign in to it through the vault until it is registered again, with a new secret.`}
        confirmLabel="Remove"
      />
      <OneTimeSecretModal secret={secret.secret} onClose={secret.clear} />
    </div>
  );
}
